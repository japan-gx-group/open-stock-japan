// AI が返した文章の後始末。サーバ依存なし。
//
// 提供元やモデルによっては、JSON の文字列の中で改行を二重にエスケープして返すことがある
// （本物の改行ではなく、バックスラッシュと n の 2 文字になる）。そのまま保存すると画面に「\n」と出るため、
// 文章として受け取る値は必ずここを通す。

/** 文字としての \n・\r\n・\t を本物の改行・タブに直し、改行コードを LF にそろえる */
export const normalizeAiText = (value: string): string =>
  value
    .replace(/\\r\\n|\\n|\\r/g, '\n')
    .replace(/\\t/g, '\t')
    .replace(/\r\n?/g, '\n');
